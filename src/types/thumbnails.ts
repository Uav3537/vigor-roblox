import z from "zod";
import type {
    RobloxAssetId, RobloxBadgeId, RobloxBundleId, RobloxDeveloperProductId, RobloxGamePassId, RobloxGameThumbnailId,
    RobloxGroupId, RobloxOutfitId, RobloxPlaceId, RobloxUniverseId,
} from "./common";
import { RobloxUniverseIdSchema } from "./common";
import type { RobloxUserId } from "./users";

/** `ThumbnailResponse.state` */
export const RobloxThumbnailStateSchema = z.enum(["Error", "Completed", "InReview", "Pending", "Blocked", "TemporarilyUnavailable"])

export type RobloxThumbnailState = z.infer<typeof RobloxThumbnailStateSchema>

/** GET /v1/assets 등의 `returnPolicy`. AutoGenerated 계열은 권한이 있는 계정만 쓸 수 있다 (없으면 403). */
export const RobloxThumbnailReturnPolicySchema = z.enum(["PlaceHolder", "ForcePlaceHolder", "AutoGenerated", "ForceAutoGenerated"])

export type RobloxThumbnailReturnPolicy = z.infer<typeof RobloxThumbnailReturnPolicySchema>


// ── 타입별 크기 / 포맷 (스펙의 GET 엔드포인트 enum 기준) ──────────
// 스펙은 게임 아이콘에 Ico/Icns도 적지만 실제로는 GET/batch 모두 400(code 2)이라 뺐다.

