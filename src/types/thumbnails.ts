export type RobloxThumbnailSize<T extends keyof typeof RobloxThumbnailSizes> = z.infer<typeof RobloxThumbnailSizes[T]>

type PngJpegWebp = "Png" | "Jpeg" | "Webp"
type PngWebp = "Png" | "Webp"


// ── 대상 ───────────────────────────────────────────────
// 엔드포인트가 아니라 "무엇의 썸네일인가"로 고른다. 어느 엔드포인트로 보낼지는 라이브러리가 정한다.

type Id<I> = { targetId: I }
/** 게임 서버 목록의 플레이어 토큰. targetId 대신 쓴다 (라이브러리가 서버 목록의 헤드샷을 받을 때 쓴다). */
type UserIdOrToken = Id<RobloxUserId> | { token: string }

type Image<T extends keyof typeof RobloxThumbnailSizes, F extends string> = {
    type:        T
    size?:       RobloxThumbnailSize<T>
    format?:     F
    isCircular?: boolean
}

/** 일부 asset은 해당 place 안에서만 볼 수 있다 (`Roblox-Place-Id` 헤더). */
type PlaceContext = { placeId?: RobloxPlaceId }

export type RobloxThumbnailTarget =
    | Image<"Avatar", PngJpegWebp> & UserIdOrToken & { includeBackground?: boolean }
    | Image<"AvatarHeadShot", PngJpegWebp> & UserIdOrToken & { includeBackground?: boolean, includeProfileFrame?: boolean }
    | Image<"AvatarBust", PngWebp> & UserIdOrToken & { includeBackground?: boolean }
    | Image<"Outfit", PngWebp> & Id<RobloxOutfitId> & { includeBackground?: boolean }
    | Image<"Asset", PngJpegWebp> & Id<RobloxAssetId> & PlaceContext & { returnPolicy?: RobloxThumbnailReturnPolicy }
    | Image<"GameIcon", PngJpegWebp> & Id<RobloxUniverseId> & { returnPolicy?: RobloxThumbnailReturnPolicy }
    | Image<"PlaceIcon", PngJpegWebp> & Id<RobloxPlaceId> & { returnPolicy?: RobloxThumbnailReturnPolicy }
    /** universeId를 주면 batch가 막혔을 때 다른 엔드포인트로도 보낼 수 있다. */
    | Image<"GameThumbnail", PngJpegWebp> & Id<RobloxGameThumbnailId> & { universeId?: RobloxUniverseId }
    | Image<"BadgeIcon", PngWebp> & Id<RobloxBadgeId>
    | Image<"GamePass", PngWebp> & Id<RobloxGamePassId>
    | Image<"BundleThumbnail", PngWebp> & Id<RobloxBundleId>
    | Image<"GroupIcon", PngWebp> & Id<RobloxGroupId>
    | Image<"DeveloperProduct", PngWebp> & Id<RobloxDeveloperProductId>
    /** batch에만 있는 타입. 가능한 크기가 문서화돼 있지 않아 size를 직접 줘야 한다. */
    | { type: "Look" | "Screenshot", size: string, format?: PngJpegWebp, isCircular?: boolean } & (Id<number> | { token: string })
    | { type: "CreatorContextAsset", size: string, format?: PngJpegWebp, isCircular?: boolean, accessContext?: string, headShape?: string } & Id<RobloxAssetId> & PlaceContext
    /** 애니메이션 asset 썸네일. 크기/포맷은 서버가 정한다. */
    | { type: "AnimatedAsset" } & Id<RobloxAssetId> & PlaceContext
    /** 3D 썸네일 — imageUrl은 3D 메타데이터 JSON을 가리킨다. 인증이 필요하다. */
    | { type: "Avatar3d" } & Id<RobloxUserId>
    | { type: "Outfit3d" } & Id<RobloxOutfitId>
    | { type: "Asset3d", useGltf?: boolean } & Id<RobloxAssetId> & PlaceContext

export type RobloxThumbnailType = RobloxThumbnailTarget["type"]

type DistributiveOmit<T, K extends PropertyKey> = T extends unknown ? Omit<T, K> : never

/** 유저에 붙이는 아바타 썸네일 옵션. 대상(targetId)은 유저 id로 채워진다. 기본은 150x150 Png 헤드샷 */
export type RobloxAvatarThumbnailOptions = DistributiveOmit<Extract<RobloxThumbnailTarget, { type: "AvatarHeadShot" | "Avatar" | "AvatarBust" }>, "targetId" | "token">

/** 그룹에 붙이는 아이콘 옵션. 기본은 150x150 Png */
export type RobloxGroupIconOptions = Omit<Extract<RobloxThumbnailTarget, { type: "GroupIcon" }>, "targetId" | "type">

/** 배지에 붙이는 아이콘 옵션. 기본은 150x150 Png */
export type RobloxBadgeIconOptions = Omit<Extract<RobloxThumbnailTarget, { type: "BadgeIcon" }>, "targetId" | "type">

/**
 * 썸네일을 붙인 결과. 썸네일이 없으면 `state`가 "Error" 등이고 `imageUrl`이 null이다.
 * 썸네일 요청 자체가 실패하면 null이다 (주 결과는 그대로 돌려준다).
 */
export type RobloxWithThumbnail<T> = T & { thumbnail: RobloxThumbnail | null }


// ── 결과 ───────────────────────────────────────────────

/** `ThumbnailResponse` — 어느 엔드포인트로 받았든 같은 모양 */
export const RobloxThumbnailSchema = z.object({
    targetId: z.number(),
    state:    RobloxThumbnailStateSchema,
    imageUrl: z.string().nullable(),
    version:  z.string().nullable(),
})

/**
 * 썸네일 하나. `I`는 대상 id의 타입이다 — `thumbnails.get()`은 넣은 대상에 맞춰 채운다
 * (유저 아바타면 `RobloxUserId`, 게임 아이콘이면 `RobloxUniverseId` …). 토큰으로 요청했으면 `number`.
 */
export type RobloxThumbnail<I extends number = number> = Omit<z.infer<typeof RobloxThumbnailSchema>, "targetId"> & { targetId: I }

/** 대상의 id 타입. 토큰으로 요청한 아바타는 `number` */
export type RobloxThumbnailTargetIdOf<T extends RobloxThumbnailTarget> = T extends { targetId: infer I extends number } ? I : number

/** `ThumbnailBatchResponse` — POST /v1/batch 의 항목 */
export const RobloxThumbnailBatchItemSchema = RobloxThumbnailSchema.extend({
    requestId:    z.string().nullable(),
    errorCode:    z.number(),
    errorMessage: z.string(),
})

/** `UniverseThumbnailsResponse` — GET /v1/games/multiget/thumbnails 의 항목 */
export const RobloxUniverseThumbnailsSchema = z.object({
    universeId: RobloxUniverseIdSchema,
    error:      z.object({ code: z.number(), message: z.string() }).nullable(),
    thumbnails: z.array(RobloxThumbnailSchema),
})

export type RobloxUniverseThumbnails = z.infer<typeof RobloxUniverseThumbnailsSchema>

export const RobloxThumbnailsResponseSchema = z.object({ data: z.array(RobloxThumbnailSchema) })
export const RobloxThumbnailBatchResponseSchema = z.object({ data: z.array(RobloxThumbnailBatchItemSchema) })
export const RobloxUniverseThumbnailsResponseSchema = z.object({ data: z.array(RobloxUniverseThumbnailsSchema) })


// ── 요청 ───────────────────────────────────────────────

/** GET /v1/games/multiget/thumbnails */
export type RobloxUniverseThumbnailsQuery = {
    /** universe당 최대 개수 */
    countPerUniverse?: number
    /** 썸네일이 없으면 기본 이미지를 넣는다 */
    defaults?:         boolean
    size?:             RobloxThumbnailSize<"GameThumbnail">
    format?:           PngJpegWebp
    isCircular?:       boolean
}
